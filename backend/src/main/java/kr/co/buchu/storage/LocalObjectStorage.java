package kr.co.buchu.storage;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.time.Duration;
import java.util.UUID;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

final class LocalObjectStorage implements ObjectStorage {
    private final Path root;

    LocalObjectStorage(String directory) {
        root = Path.of(directory).toAbsolutePath().normalize();
    }

    @Override
    public boolean remote() { return false; }

    @Override
    public PresignedTarget presign(String key, String type, long size, Duration lifetime) {
        throw new UnsupportedOperationException("Local upload capabilities are generated by UploadService");
    }

    @Override
    public void putLocal(String key, String type, long size, InputStream input) {
        Path target = resolve(key);
        Path temporary = target.resolveSibling(UUID.randomUUID() + ".part");
        try {
            byte[] bytes = ImageFiles.readLimited(input, size);
            ImageFiles.validateSignature(type, bytes);
            Files.createDirectories(target.getParent());
            Files.write(temporary, bytes);
            Files.move(temporary, target, StandardCopyOption.REPLACE_EXISTING);
        } catch (IOException error) {
            throw unavailable();
        } finally {
            try { Files.deleteIfExists(temporary); } catch (IOException ignored) { /* Best-effort temporary cleanup. */ }
        }
    }

    @Override
    public VerifiedObject inspect(String key) {
        Path path = resolve(key);
        try (InputStream input = Files.newInputStream(path)) {
            return new VerifiedObject(Files.size(path), null, input.readNBytes(32), null);
        } catch (java.nio.file.NoSuchFileException error) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "먼저 이미지를 업로드해 주세요.");
        } catch (IOException error) {
            throw unavailable();
        }
    }

    @Override
    public void copy(String sourceKey, String targetKey, String sourceEtag) {
        Path target = resolve(targetKey);
        try {
            Files.createDirectories(target.getParent());
            Files.copy(resolve(sourceKey), target);
        } catch (IOException error) {
            throw unavailable();
        }
    }

    @Override
    public void delete(String key) {
        try { Files.deleteIfExists(resolve(key)); } catch (IOException ignored) { /* Safe to clean staging later. */ }
    }

    @Override
    public byte[] read(String key, long expectedSize) {
        try (InputStream input = Files.newInputStream(resolve(key))) {
            return ImageFiles.readLimited(input, expectedSize);
        } catch (java.nio.file.NoSuchFileException error) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "이미지를 찾을 수 없습니다.");
        } catch (IOException error) {
            throw unavailable();
        }
    }

    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || !key.matches("[a-zA-Z0-9/_.-]+") || key.contains("..")) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "올바르지 않은 이미지 경로입니다.");
        }
        return path;
    }

    private ResponseStatusException unavailable() {
        return new ResponseStatusException(HttpStatus.SERVICE_UNAVAILABLE, "이미지 저장소를 사용할 수 없습니다. 잠시 후 다시 시도해 주세요.");
    }
}
