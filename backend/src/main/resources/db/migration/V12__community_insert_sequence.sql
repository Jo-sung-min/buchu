-- 글·댓글에 삽입 순번을 둔다. id가 무작위 UUID라서 created_at이 같은 행(같은 밀리초에 연속 저장)의
-- 순서가 비결정적이었다. 순번을 정렬의 2차 키로 써서 쓴 순서를 그대로 보존한다.
ALTER TABLE community_posts ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE community_comments ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

DROP INDEX idx_community_posts_created;
DROP INDEX idx_community_posts_category_created;
DROP INDEX idx_community_comments_post_created;

CREATE INDEX idx_community_posts_created ON community_posts (created_at, seq);
CREATE INDEX idx_community_posts_category_created ON community_posts (category, created_at, seq);
CREATE INDEX idx_community_comments_post_created ON community_comments (post_id, created_at, seq);
