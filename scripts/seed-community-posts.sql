INSERT INTO community_comments (id, post_id, content, nickname, delete_token_hash, created_at, author_id, author_type, ip_hint)
SELECT '00000000-0000-4000-8001-' || lpad(c.k::text, 12, '0'), p.id, c.content, c.nickname,
       md5('seed-comment-' || c.k),
       LEAST(p.created_at + make_interval(mins => (row_number() OVER (PARTITION BY c.n ORDER BY c.k))::int * 23 + 7), now() - interval '1 minute'),
       NULL, 'ANON', '127.0'
FROM seed_comments c
JOIN community_posts p ON p.id = '00000000-0000-4000-8000-' || lpad(c.n::text, 12, '0');

UPDATE community_posts p
SET comment_count = (SELECT COUNT(*) FROM community_comments c WHERE c.post_id = p.id)
WHERE p.id LIKE '00000000-0000-4000-8000-%';

